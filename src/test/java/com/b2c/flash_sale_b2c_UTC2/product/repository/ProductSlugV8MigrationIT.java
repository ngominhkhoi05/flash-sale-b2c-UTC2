package com.b2c.flash_sale_b2c_UTC2.product.repository;

import com.b2c.flash_sale_b2c_UTC2.common.test.AbstractPostgresIT;
import com.b2c.flash_sale_b2c_UTC2.product.entity.Category;
import com.b2c.flash_sale_b2c_UTC2.product.entity.Product;
import com.b2c.flash_sale_b2c_UTC2.product.repository.ProductRepository;
import com.b2c.flash_sale_b2c_UTC2.store.entity.Store;
import com.b2c.flash_sale_b2c_UTC2.user.entity.User;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.test.context.TestPropertySource;
import org.springframework.transaction.annotation.Transactional;

import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Integration tests for V8 migration: products.slug column.
 *
 * IMPORTANT: These tests require V8 migration to be applied to the target database.
 * Before running, apply the migration:
 *   - Dev/Prod DB: via Flyway (automatic on app startup)
 *   - Local DB: manually run src/main/resources/db/migration/V8__add_store_tier_product_slug.sql
 *
 * The tests use Flyway via application-test.yaml which points to Supabase Dev DB.
 * Once V8 is applied, all tests should PASS.
 */
@TestPropertySource(properties = {
    "spring.flyway.enabled=true",
    "spring.jpa.hibernate.ddl-auto=validate"
})
@Transactional
class ProductSlugV8MigrationIT extends AbstractPostgresIT {

    @Autowired
    private ProductRepository productRepository;

    @PersistenceContext
    private EntityManager em;

    private String generateSlug(String input) {
        return input.toLowerCase().replace(" ", "-");
    }

    private Product persistProduct(String name) {
        User u = User.builder()
                .email("slug-test-" + System.nanoTime() + "@x.com")
                .fullName("Test User")
                .status("ACTIVE")
                .build();
        em.persist(u);

        Store s = Store.builder()
                .user(u)
                .storeName("SlugTestStore" + System.nanoTime())
                .status("APPROVED")
                .build();
        em.persist(s);

        String categoryName = "SlugTestCat" + System.nanoTime();
        Category c = Category.builder()
                .name(categoryName)
                .slug(generateSlug(categoryName))
                .commissionRate(new java.math.BigDecimal("0.0500"))
                .build();
        em.persist(c);

        em.flush();

        Product p = Product.builder()
                .store(s)
                .category(c)
                .name(name)
                .slug(generateSlug(name))
                .status("ACTIVE")
                .build();
        em.persist(p);
        em.flush();
        return p;
    }

    @Test
    @DisplayName("V8: Product entity maps slug field")
    void productSlug_FieldExists() {
        Product p = persistProduct("Test Product With Spaces");
        em.clear();

        Optional<Product> found = productRepository.findById(p.getId());
        assertTrue(found.isPresent());
        assertNotNull(found.get().getSlug(), "slug should not be null after backfill");
    }

    @Test
    @DisplayName("V8: Backfill generates slug from name (lowercase, hyphen-separated)")
    void productSlug_BackfillGeneratesFromName() {
        Product p = persistProduct("Ao Thun Unisex Cao Cap 2024");
        em.flush();
        em.clear();

        Optional<Product> found = productRepository.findById(p.getId());
        assertTrue(found.isPresent());
        String slug = found.get().getSlug();
        assertNotNull(slug, "slug should be generated by backfill");
        assertTrue(slug.startsWith("ao-thun"), "slug should be lowercase with hyphens, got: " + slug);
    }

    @Test
    @DisplayName("V8: Backfill sets slug for all products (categories.slug registered in V9)")
    void productSlug_AllowsNull() {
        User u = User.builder()
                .email("nullslug-" + System.nanoTime() + "@x.com")
                .fullName("Test User")
                .status("ACTIVE")
                .build();
        em.persist(u);

        Store s = Store.builder()
                .user(u)
                .storeName("NullSlugStore" + System.nanoTime())
                .status("APPROVED")
                .build();
        em.persist(s);

        String categoryName = "NullSlugCat" + System.nanoTime();
        Category c = Category.builder()
                .name(categoryName)
                .slug(generateSlug(categoryName))
                .commissionRate(new java.math.BigDecimal("0.0500"))
                .build();
        em.persist(c);

        em.flush();

        Product p = Product.builder()
                .store(s)
                .category(c)
                .name("Special Product With Spaces")
                .slug(generateSlug("Special Product With Spaces"))
                .status("ACTIVE")
                .build();
        em.persist(p);
        em.flush();
        em.clear();

        Optional<Product> found = productRepository.findById(p.getId());
        assertTrue(found.isPresent());
        assertNotNull(found.get().getSlug(), "slug should be set by application on create");
    }

    @Test
    @DisplayName("V8: UNIQUE partial index uq_products_slug allows NULL slugs but prevents duplicate non-null slugs")
    void productSlug_UniqueIndexPreventsDuplicates() {
        Product p1 = persistProduct("Unique Slug Test Product");
        em.flush();
        em.clear();

        String slug = productRepository.findById(p1.getId()).get().getSlug();
        assertNotNull(slug);

        User u2 = User.builder()
                .email("dupslug2-" + System.nanoTime() + "@x.com")
                .fullName("Test User 2")
                .status("ACTIVE")
                .build();
        em.persist(u2);

        Store s2 = Store.builder()
                .user(u2)
                .storeName("DupSlugStore2" + System.nanoTime())
                .status("APPROVED")
                .build();
        em.persist(s2);

        String categoryName2 = "DupSlugCat2" + System.nanoTime();
        Category c2 = Category.builder()
                .name(categoryName2)
                .slug(generateSlug(categoryName2))
                .commissionRate(new java.math.BigDecimal("0.0500"))
                .build();
        em.persist(c2);

        em.flush();

        org.hibernate.Session session = em.unwrap(org.hibernate.Session.class);
        org.hibernate.query.NativeQuery q = session.createNativeQuery(
            "INSERT INTO products (store_id, category_id, name, status, slug) VALUES (:sid, :cid, :name, :status, :slug)"
        );
        q.setParameter("sid", s2.getId());
        q.setParameter("cid", c2.getId());
        q.setParameter("name", "Another Product With Same Slug");
        q.setParameter("status", "ACTIVE");
        q.setParameter("slug", slug);

        try {
            q.executeUpdate();
            em.flush();
            throw new AssertionError("Expected UNIQUE constraint violation for duplicate slug");
        } catch (org.hibernate.exception.ConstraintViolationException e) {
            String msg = e.getMessage() + " | " + e.getSQLException().getMessage();
            assertTrue(
                msg.contains("uq_products_slug") || msg.toLowerCase().contains("unique"),
                "Expected unique constraint violation, got: " + msg
            );
        }
    }
}